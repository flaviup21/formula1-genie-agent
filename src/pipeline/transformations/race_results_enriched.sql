CREATE OR REFRESH MATERIALIZED VIEW race_results_enriched (
  result_id INT COMMENT 'Primary key of the result row (results.result_id).',
  race_id INT COMMENT 'Race. Join key to races.race_id.',
  year INT COMMENT 'Championship season (calendar year).',
  round INT COMMENT 'Round number within the season (1 = season opener).',
  race_name STRING COMMENT 'Grand Prix name (e.g. \'Monaco Grand Prix\'). Combine with year to identify a single race.',
  race_date DATE COMMENT 'Date of the Grand Prix.',
  circuit_id INT COMMENT 'Circuit. Join key to circuits.circuit_id.',
  circuit_name STRING COMMENT 'Track name (e.g. \'Circuit de Monaco\').',
  circuit_city STRING COMMENT 'City or locality of the circuit.',
  circuit_country STRING COMMENT 'Country where the race was held (host country). Not the driver nationality.',
  driver_id INT COMMENT 'Driver. Join key to drivers.driver_id.',
  driver_name STRING COMMENT 'Full driver name (e.g. \'Lewis Hamilton\'). Use to filter or group by driver.',
  driver_code STRING COMMENT 'Three-letter timing-screen abbreviation (e.g. HAM). Mostly NULL for historic drivers.',
  driver_nationality STRING COMMENT 'Driver nationality as an adjective (e.g. \'British\').',
  date_of_birth DATE COMMENT 'Driver date of birth; use with race_date for age at the race.',
  constructor_id INT COMMENT 'Constructor. Join key to constructors.constructor_id.',
  constructor_name STRING COMMENT 'Team name (e.g. \'Ferrari\', \'Red Bull\').',
  constructor_nationality STRING COMMENT 'Constructor nationality as an adjective (e.g. \'Italian\').',
  grid_position INT COMMENT 'Starting grid position (1 = pole). 0 means a pit lane start.',
  finish_position INT COMMENT 'Official finishing position. NULL if not classified.',
  position_order INT COMMENT 'Ordering of all entrants (1..N) including non-finishers. Use for sorting only.',
  position_text STRING COMMENT 'Finishing position as text: a number, or R = retired, D = disqualified, N = not classified, W = withdrawn, F = failed to qualify, E = excluded.',
  points DOUBLE COMMENT 'Grand Prix points scored (sprint points excluded), under the scoring system of that season.',
  laps_completed INT COMMENT 'Number of laps completed.',
  race_time_ms BIGINT COMMENT 'Total race time in milliseconds. NULL for lapped drivers or non-finishers.',
  fastest_lap_rank INT COMMENT 'Rank of the driver\'s fastest lap in the race (1 = fastest lap of the race). NULL before 2004.',
  fastest_lap_time STRING COMMENT 'Driver\'s fastest lap time as text (m:ss.sss).',
  fastest_lap_speed_kph DOUBLE COMMENT 'Average speed of the driver\'s fastest lap in km/h.',
  status STRING COMMENT 'Finishing status: \'Finished\', \'+N Lap(s)\' or the retirement reason (e.g. \'Engine\').',
  is_win BOOLEAN COMMENT 'TRUE if the driver won the race (finish_position = 1).',
  is_podium BOOLEAN COMMENT 'TRUE if the driver finished in the top 3.',
  is_pole_start BOOLEAN COMMENT 'TRUE if the driver started from grid position 1. Based on the grid after penalties, not qualifying.',
  is_fastest_lap BOOLEAN COMMENT 'TRUE if the driver set the fastest lap of the race.',
  is_classified_finish BOOLEAN COMMENT 'TRUE if the status is \'Finished\' or \'+N Lap(s)\'. Use for reliability / DNF analysis.',
  positions_gained INT COMMENT 'Grid position minus finish position (positive = places gained). NULL for pit lane starts or non-classified finishes.'
)
COMMENT 'Denormalized fact: Grand Prix race results joined with race, circuit, driver, constructor and status. One row per driver per race. Use for most analytics.'
AS SELECT
  r.result_id,
  r.race_id,
  ra.year,
  ra.round,
  ra.race_name,
  ra.race_date,
  ra.circuit_id,
  c.circuit_name,
  c.city AS circuit_city,
  c.country AS circuit_country,
  r.driver_id,
  d.driver_name,
  d.driver_code,
  d.nationality AS driver_nationality,
  d.date_of_birth,
  r.constructor_id,
  co.constructor_name,
  co.nationality AS constructor_nationality,
  r.grid_position,
  r.finish_position,
  r.position_order,
  r.position_text,
  r.points,
  r.laps_completed,
  r.race_time_ms,
  r.fastest_lap_rank,
  r.fastest_lap_time,
  r.fastest_lap_speed_kph,
  s.status,
  r.finish_position = 1 AS is_win,
  r.finish_position <= 3 AS is_podium,
  r.grid_position = 1 AS is_pole_start,
  r.fastest_lap_rank = 1 AS is_fastest_lap,
  (s.status = 'Finished' OR s.status LIKE '+%') AS is_classified_finish,
  CASE WHEN r.grid_position > 0 THEN r.grid_position - r.finish_position END AS positions_gained
FROM results r
JOIN races ra ON r.race_id = ra.race_id
JOIN circuits c ON ra.circuit_id = c.circuit_id
JOIN drivers d ON r.driver_id = d.driver_id
JOIN constructors co ON r.constructor_id = co.constructor_id
LEFT JOIN status s ON r.status_id = s.status_id;
